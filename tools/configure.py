#!/usr/bin/env python3
"""Detect host tools and write config.mk; Make never performs discovery.
main accepts explicit paths or environment overrides, finds optional runtime tools,
and validates the core compiler/linker before publishing settings.
"""

import argparse
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys


PROJECT = Path(__file__).resolve().parents[1]


def executable(value):
    found = shutil.which(value) if value else None
    return os.path.abspath(found) if found else ''


def first_file(paths):
    return next((str(path.absolute()) for path in paths if path.is_file()), '')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=PROJECT / 'config.mk')
    parser.add_argument('--force', action='store_true', help='replace existing generated settings')
    for name in ('ldc', 'lld-link', 'qemu', 'ovmf-code', 'qemu-display', 'druntime-cc'):
        parser.add_argument('--' + name, default=os.environ.get(name.upper().replace('-', '_')))
    args = parser.parse_args()
    if args.output.exists() and not args.force:
        print(f'{args.output} already exists; use --force to regenerate.')
        return

    ldc = executable(args.ldc if args.ldc is not None else 'ldc2')
    if not ldc and args.ldc is None:
        ldc = next((found for path in sorted((PROJECT / 'build/tools').glob('ldc2-1.43.0-*/bin/ldc2'))
                    if (found := executable(str(path)))), '')
    linker = executable(args.lld_link if args.lld_link is not None else 'lld-link')
    if not linker and args.lld_link is None and shutil.which('rustc'):
        result = subprocess.run(['rustc', '--print', 'target-libdir'],
                                capture_output=True, text=True, timeout=15)
        if result.returncode == 0 and result.stdout.strip():
            linker = executable(str(Path(result.stdout.strip()).parent / 'bin/gcc-ld/lld-link'))
    if not ldc or not linker:
        parser.error('LDC and lld-link are required. Install them or pass --ldc and --lld-link.')

    qemu = executable(args.qemu if args.qemu is not None else 'qemu-system-x86_64')
    firmware = []
    if qemu:
        firmware.append(Path(qemu).parent.parent / 'share/qemu/edk2-x86_64-code.fd')
    firmware += [Path(path) for path in (
        '/usr/share/OVMF/OVMF_CODE_4M.fd', '/usr/share/OVMF/OVMF_CODE.fd',
        '/usr/share/edk2/ovmf/OVMF_CODE.fd', '/usr/share/edk2-ovmf/x64/OVMF_CODE.4m.fd',
    )]
    ovmf = first_file([Path(args.ovmf_code)] if args.ovmf_code is not None else firmware)
    cc = executable(args.druntime_cc if args.druntime_cc is not None else 'clang')
    for name, explicit, found in (
        ('qemu', args.qemu, qemu),
        ('ovmf-code', args.ovmf_code, ovmf), ('druntime-cc', args.druntime_cc, cc),
    ):
        if explicit is not None and not found:
            parser.error(f'--{name}: path not found or unusable: {explicit}')
    display = args.qemu_display
    if display is None:
        display = 'cocoa,zoom-to-fit=on' if platform.system() == 'Darwin' else ''
    values = dict(LDC=ldc, LLD_LINK=linker, PYTHON=sys.executable, QEMU=qemu,
                  OVMF_CODE=ovmf, QEMU_DISPLAY=display, DRUNTIME_CC=cc)
    lines = ['# Generated by ./configure; local settings, not version controlled.']
    for name, value in values.items():
        if '\n' in value or '\r' in value:
            parser.error(f'{name}: newlines are not supported')
        escaped = value.replace('$', '$$').replace('#', '\\#')
        lines.append(f'{name} := {escaped}')
    with args.output.open('w' if args.force else 'x') as output:
        output.write('\n'.join(lines) + '\n')
    print(f'Created {args.output}:')
    print('\n'.join(lines[1:]))
    for name in ('QEMU', 'OVMF_CODE', 'DRUNTIME_CC'):
        if not values[name]:
            print(f'{name}: not found; configure it before using targets that require it.')


if __name__ == '__main__':
    main()
